"""Source-only F001 byte-canonicality regression tests; no PostgreSQL or Product writes.

The frozen golden is generated by a synthetic Node JSON.stringify oracle, not
by native execution of the real Product JS/Zod runtime (separate IR003 advisory).
"""
from __future__ import annotations

from dataclasses import replace
from hashlib import sha256
import json
import unittest

from test_bridge import FakeConn, GOLDEN, mutation, genesis
from ts_global.bridge import StorageRejected, apply, initialize, read
from ts_global import legacy_v0


class CanonicalEventBytesTests(unittest.TestCase):
    def setUp(self):
        self.conn = FakeConn()
        self.scope = GOLDEN["scope"]
        initialize(self.conn, self.scope, genesis())

    @staticmethod
    def forged(m, payload_bytes):
        digest = sha256(payload_bytes).hexdigest().encode("ascii")
        line = payload_bytes[:-1] + b',"hash":"' + digest + b'"}\n'
        return replace(m, payload_bytes=payload_bytes, event_line=line)

    def reject_without_sql(self, forged, error="EVENT_JS_BYTES_MISMATCH"):
        before = self.conn.queries
        with self.assertRaisesRegex(StorageRejected, error):
            apply(self.conn, forged)
        self.assertEqual(before, self.conn.queries)

    def test_01_all_frozen_node_payloads_are_byte_identical(self):
        for i in range(len(GOLDEN["mutations"])):
            with self.subTest(sequence=i + 1):
                m = mutation(i)
                self.assertEqual(legacy_v0.exact_js_event_payload(json.loads(m.payload_bytes)), m.payload_bytes)

    def test_02_payload_whitespace_with_matching_hash_rejected(self):
        m = mutation(0)
        modified = m.payload_bytes.replace(b',"sequence":', b', "sequence":', 1)
        self.assertNotEqual(modified, m.payload_bytes)
        self.reject_without_sql(self.forged(m, modified))

    def test_03_payload_pretty_printed_with_matching_hash_rejected(self):
        m = mutation(0)
        modified = json.dumps(json.loads(m.payload_bytes), indent=2, ensure_ascii=False).encode("utf-8")
        self.reject_without_sql(self.forged(m, modified))

    def test_04_property_order_not_product_order_rejected(self):
        m = mutation(0)
        payload = json.loads(m.payload_bytes)
        keys = list(payload)
        changed = {key: payload[key] for key in [keys[1], keys[0], *keys[2:]]}
        modified = legacy_v0.exact_js_event_payload(changed)
        self.assertNotEqual(modified, m.payload_bytes)
        # Canonical JSON.stringify for a *different object* is insufficient:
        # Product V0 creates top-level payload keys in the fixed source order.
        self.reject_without_sql(self.forged(m, modified), "PRODUCT_V0_EVENT_MISMATCH")

    def test_05_unicode_escape_not_product_original_bytes(self):
        m = next(mutation(i) for i in range(len(GOLDEN["mutations"]))
                 if any(byte >= 128 for byte in mutation(i).payload_bytes))
        modified = json.dumps(json.loads(m.payload_bytes), ensure_ascii=True,
                              separators=(",", ":")).encode("ascii")
        self.assertNotEqual(modified, m.payload_bytes)
        self.reject_without_sql(self.forged(m, modified))

    def test_06_escaped_ascii_property_name_rejected(self):
        m = mutation(0)
        modified = m.payload_bytes.replace(b'"id":', b'"\\u0069d":', 1)
        self.reject_without_sql(self.forged(m, modified))

    def test_07_escaped_solidus_rejected(self):
        m = mutation(0)
        self.assertIn(b"/", m.payload_bytes)
        modified = m.payload_bytes.replace(b"/", b"\\/", 1)
        self.reject_without_sql(self.forged(m, modified))

    def test_08_negative_zero_noncanonical_with_hash_rejected(self):
        m = mutation(0)
        modified = m.payload_bytes.replace(b'"sequence":1', b'"sequence":-0', 1)
        self.assertNotEqual(modified, m.payload_bytes)
        self.reject_without_sql(self.forged(m, modified))

    def test_09_array_index_keys_follow_ecmascript_order(self):
        obj = {"after": {"10": "ten", "2": "two", "4294967295": 5,
                         "4294967294": 4, "alpha": "Ñ🥰", "ctrl": "\n\b"}}
        expected = ('{"after":{"2":"two","10":"ten","4294967294":4,'
                    '"4294967295":5,"alpha":"Ñ🥰","ctrl":"\\n\\b"}}').encode("utf-8")
        self.assertEqual(legacy_v0.exact_js_event_payload(obj), expected)

    def test_10_read_rejects_tamper_even_if_hashes_recomputed(self):
        m = mutation(0)
        apply(self.conn, m)
        modified = m.payload_bytes.replace(b',"sequence":', b', "sequence":', 1)
        forged = self.forged(m, modified)
        newhash = sha256(modified).hexdigest()
        row = self.conn.events[(self.scope, 1)]
        row["payload_bytes"] = modified
        row["event_hash"] = newhash
        row["event_line"] = forged.event_line
        self.conn.heads[self.scope]["last_event_hash"] = newhash
        self.conn.heads[self.scope]["events_sha256"] = sha256(forged.event_line).hexdigest()
        with self.assertRaisesRegex(StorageRejected, "EVENT_JS_BYTES_MISMATCH"):
            read(self.conn, self.scope)

    def test_11_surrogate_event_id_is_not_valid_event_sequence(self):
        m = mutation(0)
        modified = m.payload_bytes.replace(b'"id":"event-1"',
                                           b'"id":"\\ud800"', 1)
        self.assertNotEqual(modified, m.payload_bytes)
        self.reject_without_sql(self.forged(m, modified), "INVALID_EVENT_ID")


if __name__ == "__main__":
    unittest.main()
